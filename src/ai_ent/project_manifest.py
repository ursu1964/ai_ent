def _classify_trace_warnings(findings: tuple[TraceFinding, ...]) -> tuple[ClassifiedTraceWarning, ...]:
    warnings = []
    for finding in findings:
        if finding.severity != "WARNING":
            continue
        classification: WarningClassification = "PLANNING_RELEVANT" if finding.finding_id.endswith("-GAP") else "INFORMATIONAL"
        if "FUTURE" in finding.message.upper() or "deferred" in finding.message.lower():
            classification = "REQUIRES_FUTURE_DECISION"
        warnings.append(ClassifiedTraceWarning(finding.finding_id, finding.subject_id, classification, finding.message))
    return tuple(sorted(warnings, key=lambda item: item.finding_id))


def _task_cycle(dependencies: dict[str, set[str]]) -> list[str]:
    visiting: set[str] = set()
    visited: set[str] = set()

    def visit(task_id: str, path: list[str]) -> list[str]:
        if task_id in visiting:
            return path[path.index(task_id):]
        if task_id in visited:
            return []
        visiting.add(task_id)
        for dependency in sorted(dependencies.get(task_id, set())):
            cycle = visit(dependency, [*path, dependency])
            if cycle:
                return cycle
        visiting.remove(task_id)
        visited.add(task_id)
        return []

    for task_id in sorted(dependencies):
        cycle = visit(task_id, [task_id])
        if cycle:
            return cycle
    return []


