@dataclass(frozen=True)
class ImplementationPlan:
    source_compiled_hash: str
    capability_resolution_hash: str
    trace_validation_hash: str
    generator_version: str
    implementation_plan_hash: str
    epics: tuple[dict[str, Any], ...]
    features: tuple[dict[str, Any], ...]
    tasks: tuple[GeneratedImplementationTask, ...]
    satisfied_units: tuple[SatisfiedPlanningUnit, ...]
    dependency_edges: tuple[tuple[str, str], ...]
    waves: tuple[dict[str, Any], ...]
    parallelizable_sets: tuple[dict[str, Any], ...]
    critical_path: tuple[str, ...]
    human_gates: tuple[dict[str, Any], ...]
    findings: tuple[ImplementationPlanFinding, ...]
    warning_classifications: tuple[ClassifiedTraceWarning, ...]

    @property
    def ok(self) -> bool:
        return not any(finding.severity == "ERROR" for finding in self.findings)

    def as_dict(self) -> dict[str, Any]:
        risk_distribution: dict[str, int] = {}
        tasks_by_capability: dict[str, int] = {}
        tasks_by_component: dict[str, int] = {}
        for task in self.tasks:
            risk_level = task.risk["level"]
            risk_distribution[risk_level] = risk_distribution.get(risk_level, 0) + 1
            for capability_id in task.implements["capabilities"]:
                tasks_by_capability[capability_id] = tasks_by_capability.get(capability_id, 0) + 1
            for component_id in task.implements["components"]:
                tasks_by_component[component_id] = tasks_by_component.get(component_id, 0) + 1
        return {
            "generated": GENERATED_MARKER,
            "source_compiled_hash": self.source_compiled_hash,
            "capability_resolution_hash": self.capability_resolution_hash,
            "trace_validation_hash": self.trace_validation_hash,
            "generator_version": self.generator_version,
            "implementation_plan_hash": self.implementation_plan_hash,
            "epics": list(self.epics),
            "features": list(self.features),
            "tasks": [task.as_dict() for task in self.tasks],
            "satisfied_units": [unit.as_dict() for unit in self.satisfied_units],
            "dependency_edges": [list(edge) for edge in self.dependency_edges],
            "waves": list(self.waves),
            "parallelizable_sets": list(self.parallelizable_sets),
            "critical_path": list(self.critical_path),
            "human_gates": list(self.human_gates),
            "findings": [finding.as_dict() for finding in self.findings],
            "warning_classifications": [warning.as_dict() for warning in self.warning_classifications],
            "summary": {
                "epic_count": len(self.epics),
                "feature_count": len(self.features),
                "executable_task_count": len(self.tasks),
                "already_satisfied_planning_units": len(self.satisfied_units),
                "dependency_edge_count": len(self.dependency_edges),
                "wave_count": len(self.waves),
                "maximum_parallel_width": max((len(wave["task_ids"]) for wave in self.waves), default=0),
                "critical_path_task_count": len(self.critical_path),
                "human_gate_count": len(self.human_gates),
                "risk_distribution": dict(sorted(risk_distribution.items())),
                "tasks_by_capability": dict(sorted(tasks_by_capability.items())),
                "tasks_by_component": dict(sorted(tasks_by_component.items())),
                "finding_error_count": len([finding for finding in self.findings if finding.severity == "ERROR"]),
                "finding_warning_count": len([finding for finding in self.findings if finding.severity == "WARNING"]),
            },
        }


def validate_project_manifest(root: Path = PROJECT_MANIFEST_ROOT) -> ManifestValidationResult:
    documents = load_manifest_documents(root)
    errors: list[str] = []
    warnings: list[str] = []

    project = _parse_project(documents, errors)
    source_ids = {source.id for source in project.source_corpus} if project else set()
    source_ids.add("BEAG-001")

    capabilities = _parse_capabilities(documents, errors)
    capability_ids = {capability.id for capability in capabilities}
    _validate_unique_ids(documents, errors)
    _validate_source_refs(documents, source_ids, errors)
    _validate_capability_dependencies(capabilities, capability_ids, errors)

    requirements = _items(documents, "requirements")
    components = _items(documents, "components")
    interfaces = _items(documents, "interfaces")
    agents = _items(documents, "agents")
    epics = _items(documents, "epics")
    features = _items(documents, "features")

    for item in [*requirements, *components, *agents]:
        _validate_capability_refs(item, capability_ids, errors)
    component_ids = {_item_id(component) for component in components}
    requirement_ids = {_item_id(requirement) for requirement in requirements}
    epic_ids = {_item_id(epic) for epic in epics}
    _validate_interfaces(interfaces, component_ids, errors)
    _validate_feature_refs(features, epic_ids, requirement_ids, errors)

    selected = tuple(sorted(capability.id for capability in capabilities if capability.status in {"REQUIRED", "CONDITIONAL"}))
    already = tuple(sorted(capability.id for capability in capabilities if capability.maturity in {"VALIDATED", "PRODUCTION_READY"}))
    missing = tuple(
        sorted(
            capability.id
            for capability in capabilities
            if capability.status == "REQUIRED" and capability.maturity not in {"VALIDATED", "PRODUCTION_READY"}
        )
    )
    unresolved = _unresolved_decisions(documents)
    if not unresolved:
        warnings.append("no unresolved decisions recorded")

    return ManifestValidationResult(
        manifest_files=tuple(sorted(str(path.relative_to(root)) for path in documents)),
        requirements_count=len(requirements),
        components_count=len(components),
        interfaces_count=len(interfaces),
        capabilities_selected=selected,
        unresolved_decisions=tuple(unresolved),
        validation_errors=tuple(errors),
        validation_warnings=tuple(warnings),
        already_satisfied=already,
        still_missing=missing,
        compilation_hash=compilation_hash(documents),
    )


def load_manifest_documents(root: Path) -> dict[Path, dict[str, Any]]:
    if not root.exists():
        raise FileNotFoundError(f"project manifest root not found: {root}")
    documents: dict[Path, dict[str, Any]] = {}
    for path in sorted(root.rglob("*.yaml")):
        loaded = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        if not isinstance(loaded, dict):
            raise TypeError(f"{path} must contain a YAML mapping")
        documents[path] = loaded
    return documents


def compile_project_manifest(root: Path = PROJECT_MANIFEST_ROOT) -> CompilationResult:
    validation = validate_project_manifest(root)
    if not validation.ok:
        raise ValueError("project manifest validation failed: " + "; ".join(validation.validation_errors))
    documents = load_manifest_documents(root)
    compiled = _compile_documents(root, documents)
    compiled_bytes = canonical_bytes(compiled.as_dict())
    compiled_hash = hashlib.sha256(compiled_bytes).hexdigest()
    lock = ManifestLock(
        project_id=str(compiled.project["id"]),
        manifest_schema_version=PROJECT_MANIFEST_SCHEMA_VERSION,
        compiler_version=PROJECT_MANIFEST_COMPILER_VERSION,
        source_file_hashes=_source_file_hashes(root, documents),
        source_compilation_hash=validation.compilation_hash,
        compiled_hash=compiled_hash,
    )
    return CompilationResult(
        compiled=compiled,
        lock=lock,
        compiled_bytes=compiled_bytes,
        validation=validation,
    )


def write_compiled_project(root: Path = PROJECT_MANIFEST_ROOT, output_dir: Path = Path(".build/compiled")) -> CompilationResult:
    result = compile_project_manifest(root)
    output_dir.mkdir(parents=True, exist_ok=True)
    _write_json(output_dir / "project.json", result.compiled.as_dict())
    _write_json(output_dir / "manifest.lock", result.lock.as_dict())
    _write_json(output_dir / "requirements.json", {"requirements": list(result.compiled.requirements)})
    _write_json(output_dir / "architecture.json", result.compiled.architecture)
    _write_json(output_dir / "capabilities.json", {"capabilities": list(result.compiled.capabilities)})
