def _feasible_parallel_width(
    plan: ImplementationPlan,
    task_results: tuple[TaskFeasibility, ...],
    policy: FeasibilityPolicyProfile,
) -> int:
    non_blocked = {result.task_id for result in task_results if result.status not in {"BLOCKED", "DEFERRED"}}
    widths = [
        len([task_id for task_id in parallel_set["task_ids"] if task_id in non_blocked])
        for parallel_set in plan.parallelizable_sets
    ]
    return min(max(widths, default=0), policy.max_parallel_width)


