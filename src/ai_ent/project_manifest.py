def _requirement_coverage(
    requirement: dict[str, Any],
    capabilities: tuple[str, ...],
    components: tuple[str, ...],
    verification: tuple[str, ...],
    capability_by_id: dict[str, ResolvedCapability],
) -> RequirementCoverage:
    if requirement.get("classification") == "FUTURE/DEFERRED":
        return "DEFERRED"
    if not capabilities or any(capability_id not in capability_by_id for capability_id in capabilities):
        return "INVALID"
    if not components or not verification:
        return "UNCOVERED"
    satisfactions = [capability_by_id[capability_id].satisfaction for capability_id in capabilities]
    if any(satisfaction == "UNSATISFIED" for satisfaction in satisfactions):
        return "BLOCKED"
    if any(satisfaction == "PARTIALLY_SATISFIED" for satisfaction in satisfactions):
        return "PARTIALLY_COVERED"
    return "COVERED"


def _requirement_findings(
    requirement: dict[str, Any],
    coverage: RequirementCoverage,
    components: tuple[str, ...],
    verification: tuple[str, ...],
    capability_by_id: dict[str, ResolvedCapability],
    findings: list[TraceFinding],
    gaps: set[str],
    deployment_mode: str,
) -> None:
    requirement_id = str(requirement["id"])
    if coverage == "INVALID":
        findings.append(TraceFinding(f"TRACE-{requirement_id}-INVALID", "ERROR", requirement_id, "invalid requirement capability reference"))
        return
    if coverage == "DEFERRED":
        findings.append(TraceFinding(f"TRACE-{requirement_id}-DEFERRED", "INFO", requirement_id, "requirement deferred from current implementation"))
        return
    if not components:
        findings.append(TraceFinding(f"TRACE-{requirement_id}-NO-ARCH", "ERROR", requirement_id, "normative requirement has no architecture path"))
    if not verification:
        findings.append(TraceFinding(f"TRACE-{requirement_id}-NO-VERIFY", "ERROR", requirement_id, "normative requirement has no verification path"))
    for capability_id in requirement.get("capabilities", []):
        capability = capability_by_id.get(str(capability_id))
        if capability is not None and capability.satisfaction in {"UNSATISFIED", "PARTIALLY_SATISFIED"}:
            gaps.add(str(capability_id))
            findings.append(
                TraceFinding(
                    f"TRACE-{requirement_id}-{capability_id}-GAP",
                    "WARNING",
                    requirement_id,
                    f"requirement depends on {capability_id} with {capability.satisfaction}",
                )
            )
    title = str(requirement.get("title", "")).lower()
    if "authentication" in title or "authenticated" in title:
        has_auth_component = any(capability_id == "C14" for capability_id in requirement.get("capabilities", []))
        if not has_auth_component:
            findings.append(
                TraceFinding(
                    f"TRACE-{requirement_id}-AUTH-ARCH",
                    "ERROR",
                    requirement_id,
                    "authentication requirement lacks user/tenant management capability",
                )
            )
    if "production" in title and "deployment" in title and deployment_mode == "local_development":
        findings.append(
            TraceFinding(
                f"TRACE-{requirement_id}-DEPLOYMENT-CONFLICT",
                "ERROR",
                requirement_id,
                "current-release production deployment requirement conflicts with local_development deployment mode",
            )
        )


def _architecture_coverage(
    components: list[dict[str, Any]],
    interfaces: list[dict[str, Any]],
    requirements: list[dict[str, Any]],
    decisions: list[dict[str, Any]],
    edges: list[TraceEdge],
    findings: list[TraceFinding],
) -> tuple[ArchitectureTrace, ...]:
    requirement_by_capability = _requirements_by_capability(requirements)
    decision_sources = {str(source) for decision in decisions for source in decision.get("source_refs", [])}
    coverage: list[ArchitectureTrace] = []
    for component in sorted(components, key=lambda item: str(item["id"])):
        component_id = str(component["id"])
        if component.get("classification") == "FUTURE/DEFERRED":
            coverage.append(ArchitectureTrace(component_id, "component", "DEFERRED", tuple(component.get("source_refs", []))))
            continue
        justified_by = sorted({
            requirement_id
            for capability_id in component.get("capabilities", [])
            for requirement_id in requirement_by_capability.get(str(capability_id), set())
        })
        if not justified_by:
            justified_by = sorted({str(source) for source in component.get("source_refs", [])} & decision_sources)
        if justified_by:
            coverage.append(ArchitectureTrace(component_id, "component", "JUSTIFIED", tuple(justified_by)))
            for requirement_id in justified_by:
                edges.append(TraceEdge(component_id, requirement_id, "JUSTIFIED_BY"))
        else:
            coverage.append(ArchitectureTrace(component_id, "component", "ORPHANED", ()))
            findings.append(TraceFinding(f"TRACE-{component_id}-ORPHAN", "ERROR", component_id, "normative component is orphaned"))
    component_ids = {str(component["id"]) for component in components}
    for interface in sorted(interfaces, key=lambda item: str(item["id"])):
        interface_id = str(interface["id"])
        if interface.get("classification") == "FUTURE/DEFERRED":
            coverage.append(ArchitectureTrace(interface_id, "interface", "DEFERRED", tuple(interface.get("source_refs", []))))
            continue
        endpoints = [str(interface.get("from_component")), str(interface.get("to_component"))]
        if all(endpoint in component_ids for endpoint in endpoints):
            coverage.append(ArchitectureTrace(interface_id, "interface", "JUSTIFIED", tuple(endpoints)))
            for endpoint in endpoints:
                edges.append(TraceEdge(interface_id, endpoint, "JUSTIFIED_BY"))
        else:
            coverage.append(ArchitectureTrace(interface_id, "interface", "ORPHANED", ()))
            findings.append(TraceFinding(f"TRACE-{interface_id}-ORPHAN", "ERROR", interface_id, "interface endpoint is unknown"))
    return tuple(coverage)


def _requirements_by_capability(requirements: list[dict[str, Any]]) -> dict[str, set[str]]:
    result: dict[str, set[str]] = {}
    for requirement in requirements:
        if requirement.get("classification") == "FUTURE/DEFERRED":
            continue
        for capability_id in requirement.get("capabilities", []):
            result.setdefault(str(capability_id), set()).add(str(requirement["id"]))
    return result


def _evaluate_task_feasibility(
    task: GeneratedImplementationTask,
    plan: ImplementationPlan,
    environment: EnvironmentProfile,
    policy: FeasibilityPolicyProfile,
) -> TaskFeasibility:
    blockers: list[str] = []
    conditions: list[str] = []
    reasons: list[str] = []

    agent = _facet(task.execution["agent_role"] in policy.agent_roles, f"agent role {task.execution['agent_role']} is available")
    if agent.status == "MISSING":
        blockers.append(f"missing agent role {task.execution['agent_role']}")

    model = _facet(task.execution["model_profile"] in policy.model_profiles, f"model profile {task.execution['model_profile']} is available")
    if model.status == "MISSING":
        blockers.append(f"missing model profile {task.execution['model_profile']}")

    executor_name = task.execution["executor"]
    tool = _tool_feasibility(executor_name, environment, policy)
    if tool.status == "MISSING":
        blockers.extend(tool.reasons)
    if tool.status == "CONDITIONAL":
        conditions.extend(tool.reasons)

    infrastructure = _infrastructure_feasibility(environment)
    if infrastructure.status == "MISSING":
        blockers.extend(infrastructure.reasons)

    resources = _resource_feasibility(task, environment)
    if resources.status == "MISSING":
        blockers.extend(resources.reasons)

    verification = _facet(
        str(task.verification["profile"]) in policy.verification_profiles,
        f"verification profile {task.verification['profile']} is available",
    )
    if verification.status == "MISSING":
        blockers.append(f"missing verification profile {task.verification['profile']}")

    scope = _write_scope_blockers(task, policy)
    blockers.extend(scope)

    dependency = _dependency_feasibility(task, plan)
    if dependency.status == "MISSING":
        blockers.extend(dependency.reasons)

    required_human_gates = tuple(sorted(gate["id"] for gate in plan.human_gates if gate["task_id"] == task.id))
    policy_decision = _policy_decision(task, policy)
    if policy_decision == "PROHIBITED":
        blockers.append("policy prohibits task execution")
    if required_human_gates:
        reasons.append("human approval gate required before execution")
    if conditions:
        reasons.append("task is feasible after configuration conditions are satisfied")
    if not blockers and not conditions and not required_human_gates:
        reasons.append("task is feasible under current guarded policy")

    if blockers:
        status: TaskFeasibilityStatus = "BLOCKED"
    elif required_human_gates:
        status = "HUMAN_APPROVAL_REQUIRED"
    elif conditions:
        status = "FEASIBLE_WITH_CONDITIONS"
    else:
        status = "FEASIBLE"

    return TaskFeasibility(
        task_id=task.id,
        status=status,
        reasons=tuple(sorted(reasons)),
        blockers=tuple(sorted(blockers)),
        conditions=tuple(sorted(conditions)),
        required_human_gates=required_human_gates,
        agent_feasibility=agent,
        model_feasibility=model,
        tool_feasibility=tool,
        infrastructure_feasibility=infrastructure,
        resource_feasibility=resources,
        verification_feasibility=verification,
        policy_decision=policy_decision,
        dependency_feasibility=dependency,
    )


def _dry_run_precondition_findings(
    plan: ImplementationPlan,
    evaluation: FeasibilityEvaluation,
) -> list[DryRunFinding]:
    findings: list[DryRunFinding] = []
    if len(plan.tasks) != len(evaluation.task_results):
        findings.append(DryRunFinding("DRYRUN-TASK-COUNT", "ERROR", "tasks", "feasibility did not evaluate every generated task"))
    if plan.source_compiled_hash != evaluation.source_compiled_hash:
        findings.append(DryRunFinding("DRYRUN-COMPILED-HASH", "ERROR", "compiled-project", "compiled hash mismatch"))
    if plan.capability_resolution_hash != evaluation.capability_resolution_hash:
        findings.append(DryRunFinding("DRYRUN-CAPABILITY-HASH", "ERROR", "capabilities", "capability resolution hash mismatch"))
    if plan.trace_validation_hash != evaluation.trace_validation_hash:
        findings.append(DryRunFinding("DRYRUN-TRACE-HASH", "ERROR", "trace", "trace validation hash mismatch"))
    if plan.implementation_plan_hash != evaluation.implementation_plan_hash:
        findings.append(DryRunFinding("DRYRUN-PLAN-HASH", "ERROR", "implementation-plan", "implementation plan hash mismatch"))
    if evaluation.technical_blockers:
        findings.append(DryRunFinding("DRYRUN-TECHNICAL-BLOCKERS", "ERROR", "feasibility", "technical blockers remain"))
    if any(result.status == "BLOCKED" for result in evaluation.task_results):
        findings.append(DryRunFinding("DRYRUN-BLOCKED-TASKS", "ERROR", "feasibility", "one or more tasks are blocked"))
    if any(result.status == "HUMAN_APPROVAL_REQUIRED" for result in evaluation.task_results):
        findings.append(DryRunFinding("DRYRUN-HUMAN-GATES", "INFO", "human-gates", "human gates are represented as stop/resume boundaries"))
    return findings


def _execution_batches(plan: ImplementationPlan, effective_width: int) -> tuple[ExecutionBatch, ...]:
    gate_by_task = {str(gate["task_id"]): str(gate["id"]) for gate in plan.human_gates}
    ordered_tasks = [task_id for wave in plan.waves for task_id in wave["task_ids"]]
    batches: list[ExecutionBatch] = []
    current: list[str] = []
    resume_after: str | None = None

    def flush() -> None:
        nonlocal current, resume_after
        if current:
            batches.append(
                ExecutionBatch(
                    id=f"RUN-BATCH-{len(batches) + 1:03d}",
                    task_ids=tuple(current),
                    required_human_gates=(),
                    resume_after=resume_after,
                )
            )
            current = []
            resume_after = None

    for task_id in ordered_tasks:
        gate_id = gate_by_task.get(task_id)
        if gate_id:
            flush()
            batches.append(
                ExecutionBatch(
                    id=f"RUN-BATCH-{len(batches) + 1:03d}",
                    task_ids=(task_id,),
                    required_human_gates=(gate_id,),
                    resume_after=gate_id,
                )
            )
            resume_after = gate_id
            continue
        current.append(task_id)
    flush()
    return tuple(batches)


