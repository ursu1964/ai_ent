def _requirement_coverage(
    requirement: dict[str, Any],
    capabilities: tuple[str, ...],
    components: tuple[str, ...],
    verification: tuple[str, ...],
    capability_by_id: dict[str, ResolvedCapability],
) -> RequirementCoverage:
    if requirement.get("classification") == "FUTURE/DEFERRED":
        return "DEFERRED"
    if not capabilities or any(capability_id not in capability_by_id for capability_id in capabilities):
        return "INVALID"
    if not components or not verification:
        return "UNCOVERED"
    satisfactions = [capability_by_id[capability_id].satisfaction for capability_id in capabilities]
    if any(satisfaction == "UNSATISFIED" for satisfaction in satisfactions):
        return "BLOCKED"
    if any(satisfaction == "PARTIALLY_SATISFIED" for satisfaction in satisfactions):
        return "PARTIALLY_COVERED"
    return "COVERED"


def _requirement_findings(
    requirement: dict[str, Any],
    coverage: RequirementCoverage,
    components: tuple[str, ...],
    verification: tuple[str, ...],
    capability_by_id: dict[str, ResolvedCapability],
    findings: list[TraceFinding],
    gaps: set[str],
    deployment_mode: str,
) -> None:
    requirement_id = str(requirement["id"])
    if coverage == "INVALID":
        findings.append(TraceFinding(f"TRACE-{requirement_id}-INVALID", "ERROR", requirement_id, "invalid requirement capability reference"))
        return
    if coverage == "DEFERRED":
        findings.append(TraceFinding(f"TRACE-{requirement_id}-DEFERRED", "INFO", requirement_id, "requirement deferred from current implementation"))
        return
    if not components:
        findings.append(TraceFinding(f"TRACE-{requirement_id}-NO-ARCH", "ERROR", requirement_id, "normative requirement has no architecture path"))
    if not verification:
        findings.append(TraceFinding(f"TRACE-{requirement_id}-NO-VERIFY", "ERROR", requirement_id, "normative requirement has no verification path"))
    for capability_id in requirement.get("capabilities", []):
        capability = capability_by_id.get(str(capability_id))
        if capability is not None and capability.satisfaction in {"UNSATISFIED", "PARTIALLY_SATISFIED"}:
            gaps.add(str(capability_id))
            findings.append(
                TraceFinding(
                    f"TRACE-{requirement_id}-{capability_id}-GAP",
                    "WARNING",
                    requirement_id,
                    f"requirement depends on {capability_id} with {capability.satisfaction}",
                )
            )
    title = str(requirement.get("title", "")).lower()
    if "authentication" in title or "authenticated" in title:
        has_auth_component = any(capability_id == "C14" for capability_id in requirement.get("capabilities", []))
        if not has_auth_component:
            findings.append(
                TraceFinding(
                    f"TRACE-{requirement_id}-AUTH-ARCH",
                    "ERROR",
                    requirement_id,
                    "authentication requirement lacks user/tenant management capability",
                )
            )
    if "production" in title and "deployment" in title and deployment_mode == "local_development":
        findings.append(
            TraceFinding(
                f"TRACE-{requirement_id}-DEPLOYMENT-CONFLICT",
                "ERROR",
                requirement_id,
                "current-release production deployment requirement conflicts with local_development deployment mode",
            )
        )


def _architecture_coverage(
    components: list[dict[str, Any]],
    interfaces: list[dict[str, Any]],
    requirements: list[dict[str, Any]],
    decisions: list[dict[str, Any]],
    edges: list[TraceEdge],
    findings: list[TraceFinding],
) -> tuple[ArchitectureTrace, ...]:
    requirement_by_capability = _requirements_by_capability(requirements)
    decision_sources = {str(source) for decision in decisions for source in decision.get("source_refs", [])}
    coverage: list[ArchitectureTrace] = []
    for component in sorted(components, key=lambda item: str(item["id"])):
        component_id = str(component["id"])
        if component.get("classification") == "FUTURE/DEFERRED":
            coverage.append(ArchitectureTrace(component_id, "component", "DEFERRED", tuple(component.get("source_refs", []))))
            continue
        justified_by = sorted({
            requirement_id
            for capability_id in component.get("capabilities", [])
            for requirement_id in requirement_by_capability.get(str(capability_id), set())
        })
        if not justified_by:
            justified_by = sorted({str(source) for source in component.get("source_refs", [])} & decision_sources)
        if justified_by:
            coverage.append(ArchitectureTrace(component_id, "component", "JUSTIFIED", tuple(justified_by)))
            for requirement_id in justified_by:
                edges.append(TraceEdge(component_id, requirement_id, "JUSTIFIED_BY"))
        else:
            coverage.append(ArchitectureTrace(component_id, "component", "ORPHANED", ()))
            findings.append(TraceFinding(f"TRACE-{component_id}-ORPHAN", "ERROR", component_id, "normative component is orphaned"))
    component_ids = {str(component["id"]) for component in components}
    for interface in sorted(interfaces, key=lambda item: str(item["id"])):
        interface_id = str(interface["id"])
        if interface.get("classification") == "FUTURE/DEFERRED":
            coverage.append(ArchitectureTrace(interface_id, "interface", "DEFERRED", tuple(interface.get("source_refs", []))))
            continue
        endpoints = [str(interface.get("from_component")), str(interface.get("to_component"))]
        if all(endpoint in component_ids for endpoint in endpoints):
            coverage.append(ArchitectureTrace(interface_id, "interface", "JUSTIFIED", tuple(endpoints)))
            for endpoint in endpoints:
                edges.append(TraceEdge(interface_id, endpoint, "JUSTIFIED_BY"))
        else:
            coverage.append(ArchitectureTrace(interface_id, "interface", "ORPHANED", ()))
            findings.append(TraceFinding(f"TRACE-{interface_id}-ORPHAN", "ERROR", interface_id, "interface endpoint is unknown"))
    return tuple(coverage)


