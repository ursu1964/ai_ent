def _generated_task_specs(
    compilation: CompilationResult,
    resolution: CapabilityResolution,
    trace: TraceValidationResult,
    gap_capabilities: tuple[str, ...],
    capabilities: dict[str, ResolvedCapability],
    components: dict[str, dict[str, Any]],
    component_by_capability: dict[str, set[str]],
    requirements_by_capability: dict[str, set[str]],
    trace_path_by_requirement: dict[str, TracePath],
) -> list[dict[str, Any]]:
    specs: list[dict[str, Any]] = []
    for capability_id in gap_capabilities:
        component_ids = tuple(
            sorted(
                component_id
                for component_id in component_by_capability.get(capability_id, set())
                if components.get(component_id, {}).get("implementation_state") != "VALIDATED"
            )
        )
        if component_ids:
            for component_id in component_ids:
                specs.append(
                    _implementation_task_spec(
                        compilation,
                        resolution,
                        trace,
                        capabilities[capability_id],
                        components[component_id],
                        requirements_by_capability,
                        trace_path_by_requirement,
                    )
                )
        else:
            specs.append(
                _implementation_task_spec(
                    compilation,
                    resolution,
                    trace,
                    capabilities[capability_id],
                    None,
                    requirements_by_capability,
                    trace_path_by_requirement,
                )
            )
    return sorted(specs, key=lambda item: str(item["id"]))


