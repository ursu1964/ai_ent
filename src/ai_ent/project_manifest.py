@dataclass(frozen=True)
class TraceValidationResult:
    source_compiled_hash: str
    capability_resolution_hash: str
    trace_validator_version: str
    trace_validation_hash: str
    trace_edges: tuple[TraceEdge, ...]
    trace_paths: tuple[TracePath, ...]
    architecture_coverage: tuple[ArchitectureTrace, ...]
    findings: tuple[TraceFinding, ...]
    implementation_gaps: tuple[str, ...]

    @property
    def error_count(self) -> int:
        return sum(1 for finding in self.findings if finding.severity == "ERROR")

    @property
    def warning_count(self) -> int:
        return sum(1 for finding in self.findings if finding.severity == "WARNING")

    @property
    def ok(self) -> bool:
        return self.error_count == 0

    def as_dict(self) -> dict[str, Any]:
        return {
            "generated": GENERATED_MARKER,
            "source_compiled_hash": self.source_compiled_hash,
            "capability_resolution_hash": self.capability_resolution_hash,
            "trace_validator_version": self.trace_validator_version,
            "trace_validation_hash": self.trace_validation_hash,
            "trace_edges": [edge.as_dict() for edge in self.trace_edges],
            "trace_paths": [path.as_dict() for path in self.trace_paths],
            "architecture_coverage": [item.as_dict() for item in self.architecture_coverage],
            "findings": [finding.as_dict() for finding in self.findings],
            "implementation_gaps": list(self.implementation_gaps),
            "summary": {
                "normative_requirements": len(
                    [path for path in self.trace_paths if path.coverage not in {"DEFERRED"}]
                ),
                "covered_requirements": len([path for path in self.trace_paths if path.coverage == "COVERED"]),
                "partially_covered_requirements": len(
                    [path for path in self.trace_paths if path.coverage == "PARTIALLY_COVERED"]
                ),
                "uncovered_requirements": len([path for path in self.trace_paths if path.coverage == "UNCOVERED"]),
                "deferred_requirements": len([path for path in self.trace_paths if path.coverage == "DEFERRED"]),
                "blocked_requirements": len([path for path in self.trace_paths if path.coverage == "BLOCKED"]),
                "justified_components": len(
                    [item for item in self.architecture_coverage if item.item_type == "component" and item.coverage == "JUSTIFIED"]
                ),
                "orphan_components": len(
                    [item for item in self.architecture_coverage if item.item_type == "component" and item.coverage == "ORPHANED"]
                ),
                "justified_interfaces": len(
                    [item for item in self.architecture_coverage if item.item_type == "interface" and item.coverage == "JUSTIFIED"]
                ),
                "orphan_interfaces": len(
                    [item for item in self.architecture_coverage if item.item_type == "interface" and item.coverage == "ORPHANED"]
                ),
                "error_count": self.error_count,
                "warning_count": self.warning_count,
            },
        }


