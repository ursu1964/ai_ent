def resolve_compiled_capabilities(compilation: CompilationResult) -> CapabilityResolution:
    compiled = compilation.compiled.as_dict()
    capability_rows = {str(item["id"]): item for item in compilation.compiled.capabilities}
    capability_ids = set(capability_rows)
    _validate_capability_graph_inputs(capability_rows)

    direct_dependencies: dict[str, set[str]] = {}
    applied_conditionals: dict[str, list[dict[str, Any]]] = {}
    for capability_id, row in capability_rows.items():
        direct_dependencies[capability_id] = {str(item) for item in row.get("depends_on", [])}
        applied_conditionals[capability_id] = []
        for conditional in row.get("conditional_dependencies", []):
            if not isinstance(conditional, dict):
                raise TypeError(f"{capability_id} conditional dependency must be a mapping")
            dependencies = [str(item) for item in conditional.get("capabilities", [])]
            for dependency in dependencies:
                if dependency not in capability_ids:
                    raise ValueError(f"{capability_id} conditional dependency references unknown capability {dependency}")
            if _condition_matches(compiled, conditional.get("condition", {})):
                direct_dependencies[capability_id].update(dependencies)
                applied_conditionals[capability_id].append(_normalize(conditional))
        for dependency in direct_dependencies[capability_id]:
            if dependency not in capability_ids:
                raise ValueError(f"{capability_id} depends on unknown capability {dependency}")
            if dependency == capability_id:
                raise ValueError(f"{capability_id} cannot depend on itself")

    cycle = _capability_cycle(direct_dependencies)
    if cycle:
        raise ValueError(f"capability dependency cycle: {' -> '.join(cycle)}")

    transitive = {
        capability_id: tuple(sorted(_transitive_dependencies(capability_id, direct_dependencies)))
        for capability_id in sorted(capability_ids)
    }
    required = _required_capability_set(capability_rows, direct_dependencies)
    capabilities = tuple(
        _resolve_capability(
            row,
            direct_dependencies[str(row["id"])],
            transitive[str(row["id"])],
            applied_conditionals[str(row["id"])],
            required,
        )
        for row in sorted(capability_rows.values(), key=lambda item: str(item["id"]))
    )
    direct_edges = tuple(
        sorted((capability_id, dependency) for capability_id, dependencies in direct_dependencies.items() for dependency in dependencies)
    )
    transitive_edges = tuple(
        sorted((capability_id, dependency) for capability_id, dependencies in transitive.items() for dependency in dependencies)
    )
    partial = tuple(sorted(capability.capability_id for capability in capabilities if capability.satisfaction == "PARTIALLY_SATISFIED"))
    satisfied = tuple(sorted(capability.capability_id for capability in capabilities if capability.satisfaction == "SATISFIED"))
    unsatisfied = tuple(sorted(capability.capability_id for capability in capabilities if capability.satisfaction == "UNSATISFIED"))
    deferred = tuple(sorted(capability.capability_id for capability in capabilities if capability.satisfaction in {"DEFERRED", "NOT_APPLICABLE"}))
    blocked = tuple(sorted(capability.capability_id for capability in capabilities if capability.blockers))

    payload = {
        "source_compiled_hash": compilation.lock.compiled_hash,
        "resolver_version": CAPABILITY_RESOLVER_VERSION,
        "capabilities": [capability.as_dict() for capability in capabilities],
        "direct_edges": [list(edge) for edge in direct_edges],
        "transitive_edges": [list(edge) for edge in transitive_edges],
        "required_capabilities": sorted(required),
        "conditional_capabilities_activated": sorted(
            capability_id for capability_id, conditionals in applied_conditionals.items() if conditionals
        ),
        "deferred_capabilities": list(deferred),
        "satisfied_capabilities": list(satisfied),
        "partially_satisfied_capabilities": list(partial),
        "unsatisfied_capabilities": list(unsatisfied),
        "blocked_capabilities": list(blocked),
    }
    resolution_hash = hashlib.sha256(canonical_bytes(payload)).hexdigest()
    return CapabilityResolution(
        source_compiled_hash=compilation.lock.compiled_hash,
        resolver_version=CAPABILITY_RESOLVER_VERSION,
        capability_resolution_hash=resolution_hash,
        capabilities=capabilities,
        direct_edges=direct_edges,
        transitive_edges=transitive_edges,
        required_capabilities=tuple(sorted(required)),
        conditional_capabilities_activated=tuple(payload["conditional_capabilities_activated"]),
        deferred_capabilities=deferred,
        satisfied_capabilities=satisfied,
        partially_satisfied_capabilities=partial,
        unsatisfied_capabilities=unsatisfied,
        blocked_capabilities=blocked,
    )


