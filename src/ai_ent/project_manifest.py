@dataclass(frozen=True)
class ImplementationPlan:
    source_compiled_hash: str
    capability_resolution_hash: str
    trace_validation_hash: str
    generator_version: str
    implementation_plan_hash: str
    epics: tuple[dict[str, Any], ...]
    features: tuple[dict[str, Any], ...]
    tasks: tuple[GeneratedImplementationTask, ...]
    satisfied_units: tuple[SatisfiedPlanningUnit, ...]
    dependency_edges: tuple[tuple[str, str], ...]
    waves: tuple[dict[str, Any], ...]
    parallelizable_sets: tuple[dict[str, Any], ...]
    critical_path: tuple[str, ...]
    human_gates: tuple[dict[str, Any], ...]
    findings: tuple[ImplementationPlanFinding, ...]
    warning_classifications: tuple[ClassifiedTraceWarning, ...]

    @property
    def ok(self) -> bool:
        return not any(finding.severity == "ERROR" for finding in self.findings)

    def as_dict(self) -> dict[str, Any]:
        risk_distribution: dict[str, int] = {}
        tasks_by_capability: dict[str, int] = {}
        tasks_by_component: dict[str, int] = {}
        for task in self.tasks:
            risk_level = task.risk["level"]
            risk_distribution[risk_level] = risk_distribution.get(risk_level, 0) + 1
            for capability_id in task.implements["capabilities"]:
                tasks_by_capability[capability_id] = tasks_by_capability.get(capability_id, 0) + 1
            for component_id in task.implements["components"]:
                tasks_by_component[component_id] = tasks_by_component.get(component_id, 0) + 1
        return {
            "generated": GENERATED_MARKER,
            "source_compiled_hash": self.source_compiled_hash,
            "capability_resolution_hash": self.capability_resolution_hash,
            "trace_validation_hash": self.trace_validation_hash,
            "generator_version": self.generator_version,
            "implementation_plan_hash": self.implementation_plan_hash,
            "epics": list(self.epics),
            "features": list(self.features),
            "tasks": [task.as_dict() for task in self.tasks],
            "satisfied_units": [unit.as_dict() for unit in self.satisfied_units],
            "dependency_edges": [list(edge) for edge in self.dependency_edges],
            "waves": list(self.waves),
            "parallelizable_sets": list(self.parallelizable_sets),
            "critical_path": list(self.critical_path),
            "human_gates": list(self.human_gates),
            "findings": [finding.as_dict() for finding in self.findings],
            "warning_classifications": [warning.as_dict() for warning in self.warning_classifications],
            "summary": {
                "epic_count": len(self.epics),
                "feature_count": len(self.features),
                "executable_task_count": len(self.tasks),
                "already_satisfied_planning_units": len(self.satisfied_units),
                "dependency_edge_count": len(self.dependency_edges),
                "wave_count": len(self.waves),
                "maximum_parallel_width": max((len(wave["task_ids"]) for wave in self.waves), default=0),
                "critical_path_task_count": len(self.critical_path),
                "human_gate_count": len(self.human_gates),
                "risk_distribution": dict(sorted(risk_distribution.items())),
                "tasks_by_capability": dict(sorted(tasks_by_capability.items())),
                "tasks_by_component": dict(sorted(tasks_by_component.items())),
                "finding_error_count": len([finding for finding in self.findings if finding.severity == "ERROR"]),
                "finding_warning_count": len([finding for finding in self.findings if finding.severity == "WARNING"]),
            },
        }


