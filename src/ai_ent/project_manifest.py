def _implementation_dependency_edges(
    tasks: tuple[GeneratedImplementationTask, ...],
    resolution: CapabilityResolution,
) -> tuple[tuple[str, str], ...]:
    tasks_by_capability: dict[str, list[str]] = {}
    task_by_component: dict[str, str] = {}
    for task in tasks:
        for capability_id in task.implements["capabilities"]:
            tasks_by_capability.setdefault(capability_id, []).append(task.id)
        if task.component_id:
            task_by_component[task.component_id] = task.id
    capability_dependencies = {
        capability.capability_id: capability.direct_dependencies
        for capability in resolution.capabilities
    }
    edges: set[tuple[str, str]] = set()
    for task in tasks:
        capability_id = task.implements["capabilities"][0]
        for dependency_capability in capability_dependencies.get(capability_id, ()):
            for dependency_task_id in tasks_by_capability.get(dependency_capability, []):
                if dependency_task_id != task.id:
                    edges.add((task.id, dependency_task_id))
    component_sequence = ["CMP-001", "CMP-002", "CMP-003", "CMP-004", "CMP-005", "CMP-006", "CMP-007"]
    for before, after in pairwise(component_sequence):
        before_task = task_by_component.get(before)
        after_task = task_by_component.get(after)
        if before_task and after_task and before_task != after_task:
            edges.add((after_task, before_task))
    return tuple(sorted(edges))


def _validate_implementation_plan(
    tasks: tuple[GeneratedImplementationTask, ...],
    dependency_edges: tuple[tuple[str, str], ...],
    gap_capabilities: tuple[str, ...],
) -> tuple[ImplementationPlanFinding, ...]:
    findings: list[ImplementationPlanFinding] = []
    task_ids = {task.id for task in tasks}
    covered_capabilities = {capability_id for task in tasks for capability_id in task.implements["capabilities"]}
    duplicate_task_ids = sorted({task.id for task in tasks if [candidate.id for candidate in tasks].count(task.id) > 1})
    for task_id in duplicate_task_ids:
        findings.append(ImplementationPlanFinding(f"PLAN-{task_id}-DUPLICATE", "ERROR", task_id, "duplicate generated task id"))
    for task_id, dependency_id in dependency_edges:
        if task_id == dependency_id:
            findings.append(ImplementationPlanFinding(f"PLAN-{task_id}-SELF-DEPENDENCY", "ERROR", task_id, "task depends on itself"))
        if task_id not in task_ids:
            findings.append(ImplementationPlanFinding(f"PLAN-{task_id}-MISSING", "ERROR", task_id, "dependency edge references missing task"))
        if dependency_id not in task_ids:
            findings.append(
                ImplementationPlanFinding(f"PLAN-{task_id}-{dependency_id}-MISSING-DEPENDENCY", "ERROR", task_id, "dependency edge references omitted task")
            )
    for capability_id in gap_capabilities:
        if capability_id not in covered_capabilities:
            findings.append(
                ImplementationPlanFinding(
                    f"PLAN-{capability_id}-UNCOVERED",
                    "ERROR",
                    capability_id,
                    "implementation gap has no generated task",
                )
            )
    for task in tasks:
        if not task.implements["requirements"] and not task.implements["capabilities"] and not task.implements["components"]:
            findings.append(ImplementationPlanFinding(f"PLAN-{task.id}-ORPHAN", "ERROR", task.id, "generated task has no justification"))
        if not task.verification["acceptance_criteria"]:
            findings.append(ImplementationPlanFinding(f"PLAN-{task.id}-NO-VERIFY", "ERROR", task.id, "generated task has no acceptance criteria"))
        if len(task.implements["capabilities"]) > 2 or len(task.write_scope["allowed"]) > 4:
            findings.append(ImplementationPlanFinding(f"PLAN-{task.id}-BROAD-SCOPE", "WARNING", task.id, "generated task scope should be reviewed"))
    cycle = _task_cycle({task.id: set(task.depends_on) for task in tasks})
    if cycle:
        findings.append(ImplementationPlanFinding("PLAN-CYCLE", "ERROR", "implementation-dag", f"task dependency cycle: {' -> '.join(cycle)}"))
    return tuple(sorted(findings, key=lambda item: item.finding_id))


def _implementation_waves(
    tasks: tuple[GeneratedImplementationTask, ...],
    dependency_edges: tuple[tuple[str, str], ...],
) -> list[dict[str, Any]]:
    remaining = {task.id for task in tasks}
    dependencies = {task.id: {dependency for task_id, dependency in dependency_edges if task_id == task.id} for task in tasks}
    completed: set[str] = set()
    waves: list[dict[str, Any]] = []
    while remaining:
        ready = sorted(task_id for task_id in remaining if dependencies.get(task_id, set()).issubset(completed))
        if not ready:
            raise ValueError("generated implementation DAG contains a cycle")
        waves.append({"id": f"WAVE-{len(waves) + 1:03d}", "task_ids": ready})
        completed.update(ready)
        remaining.difference_update(ready)
    return waves


def _parallelizable_sets(
    tasks: tuple[GeneratedImplementationTask, ...],
    waves: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    by_id = {task.id: task for task in tasks}
    sets: list[dict[str, Any]] = []
    for wave in waves:
        compatible: list[str] = []
        used_scopes: set[str] = set()
        for task_id in wave["task_ids"]:
            scopes = set(by_id[task_id].write_scope["allowed"])
            if not used_scopes.intersection(scopes):
                compatible.append(task_id)
                used_scopes.update(scopes)
        sets.append({"wave_id": wave["id"], "task_ids": compatible})
    return sets


def _critical_path(
    tasks: tuple[GeneratedImplementationTask, ...],
    dependency_edges: tuple[tuple[str, str], ...],
) -> tuple[str, ...]:
    dependencies = {task.id: tuple(sorted(dependency for task_id, dependency in dependency_edges if task_id == task.id)) for task in tasks}
    memo: dict[str, tuple[str, ...]] = {}

    def path_to(task_id: str) -> tuple[str, ...]:
        if task_id in memo:
            return memo[task_id]
        candidates = [path_to(dependency) for dependency in dependencies.get(task_id, ())]
        prefix = max(candidates, key=lambda path: (len(path), path), default=())
        memo[task_id] = (*prefix, task_id)
        return memo[task_id]

    paths = [path_to(task.id) for task in tasks]
    return max(paths, key=lambda path: (len(path), path), default=())


