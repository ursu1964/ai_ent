def _validate_capability_graph_inputs(capabilities: dict[str, dict[str, Any]]) -> None:
    expected = {f"C{number:02d}" for number in range(1, 21)}
    actual = set(capabilities)
    if actual != expected:
        raise ValueError(f"capability IDs must be C01-C20: missing={sorted(expected - actual)} extra={sorted(actual - expected)}")
    for capability_id, capability in capabilities.items():
        for conflict in capability.get("conflicts_with", []):
            if conflict not in capabilities:
                raise ValueError(f"{capability_id} conflicts_with unknown capability {conflict}")
            if conflict == capability_id:
                raise ValueError(f"{capability_id} cannot conflict with itself")


def _condition_matches(compiled: dict[str, Any], condition: object) -> bool:
    if not isinstance(condition, dict):
        return False
    path = condition.get("path")
    if not isinstance(path, str):
        return False
    value = _path_value(compiled, path)
    if "equals" in condition:
        return value == condition["equals"]
    if "not_equals" in condition:
        return value != condition["not_equals"]
    return False


def _path_value(value: Any, dotted_path: str) -> Any:
    current = value
    for part in dotted_path.split("."):
        if not isinstance(current, dict) or part not in current:
            return None
        current = current[part]
    return current


def _capability_cycle(dependencies: dict[str, set[str]]) -> list[str]:
    visiting: set[str] = set()
    visited: set[str] = set()

    def visit(capability_id: str, path: list[str]) -> list[str]:
        if capability_id in visiting:
            return path[path.index(capability_id):]
        if capability_id in visited:
            return []
        visiting.add(capability_id)
        for dependency in sorted(dependencies.get(capability_id, set())):
            cycle = visit(dependency, [*path, dependency])
            if cycle:
                return cycle
        visiting.remove(capability_id)
        visited.add(capability_id)
        return []

    for capability_id in sorted(dependencies):
        cycle = visit(capability_id, [capability_id])
        if cycle:
            return cycle
    return []


def _transitive_dependencies(capability_id: str, dependencies: dict[str, set[str]]) -> set[str]:
    result: set[str] = set()

    def visit(current: str) -> None:
        for dependency in sorted(dependencies.get(current, set())):
            if dependency not in result:
                result.add(dependency)
                visit(dependency)

    visit(capability_id)
    return result


def _required_capability_set(
    capabilities: dict[str, dict[str, Any]],
    direct_dependencies: dict[str, set[str]],
) -> set[str]:
    required = {capability_id for capability_id, capability in capabilities.items() if capability.get("status") == "REQUIRED"}
    expanded = set(required)
    for capability_id in sorted(required):
        expanded.update(_transitive_dependencies(capability_id, direct_dependencies))
        expanded.update(direct_dependencies.get(capability_id, set()))
    return expanded


def _resolve_capability(
    capability: dict[str, Any],
    direct_dependencies: set[str],
    transitive_dependencies: tuple[str, ...],
    applied_conditionals: list[dict[str, Any]],
    required: set[str],
) -> ResolvedCapability:
    capability_id = str(capability["id"])
    declared_status = capability["status"]
    resolved_status: ResolvedCapabilityStatus = "REQUIRED" if capability_id in required else declared_status
    maturity = capability["maturity"]
    evidence_refs = tuple(sorted(str(item) for item in capability.get("evidence_refs", [])))
    satisfaction = _satisfaction(resolved_status, maturity, evidence_refs)
    blockers = tuple(
        sorted(
            [
                f"missing implementation evidence for {capability_id}"
                for _ in [capability_id]
                if satisfaction == "UNSATISFIED"
            ]
        )
    )
    return ResolvedCapability(
        capability_id=capability_id,
        name=str(capability["name"]),
        declared_status=declared_status,
        resolved_status=resolved_status,
        maturity=maturity,
        satisfaction=satisfaction,
        direct_dependencies=tuple(sorted(direct_dependencies)),
        transitive_dependencies=transitive_dependencies,
        conditional_dependencies_applied=tuple(applied_conditionals),
        evidence_refs=evidence_refs,
        missing_requirements_components=tuple(_missing_requirements_components(capability_id, satisfaction)),
        blockers=blockers,
        source_provenance=tuple(sorted(str(item) for item in capability.get("source_refs", []))),
    )


def _satisfaction(status: str, maturity: str, evidence_refs: tuple[str, ...]) -> CapabilitySatisfaction:
    if status in {"DEFERRED", "NOT_REQUIRED"}:
        return "DEFERRED" if status == "DEFERRED" else "NOT_APPLICABLE"
    if status == "CONDITIONAL" and maturity == "NOT_IMPLEMENTED":
        return "NOT_APPLICABLE"
    if maturity in {"VALIDATED", "PRODUCTION_READY"}:
        return "SATISFIED"
    if maturity == "DEVELOPMENT":
        return "PARTIALLY_SATISFIED"
    if evidence_refs:
        return "PARTIALLY_SATISFIED"
    return "UNSATISFIED"


def _missing_requirements_components(capability_id: str, satisfaction: CapabilitySatisfaction) -> list[str]:
    if satisfaction in {"SATISFIED", "NOT_APPLICABLE", "DEFERRED"}:
        return []
    return [f"{capability_id}:implementation"]


def _parse_project(documents: dict[Path, dict[str, Any]], errors: list[str]) -> ProjectDocument | None:
    project_path = next((path for path in documents if path.name == "project.yaml"), None)
    if project_path is None:
        errors.append("missing project.yaml")
        return None
    try:
        return ProjectDocument.model_validate(documents[project_path])
    except ValidationError as exc:
        errors.append(f"project.yaml schema error: {_compact_validation(exc)}")
        return None


def _parse_capabilities(documents: dict[Path, dict[str, Any]], errors: list[str]) -> list[Capability]:
    path = next((candidate for candidate in documents if candidate.name == "capabilities.yaml"), None)
    if path is None:
        errors.append("missing capabilities.yaml")
        return []
    raw = documents[path].get("capabilities", [])
    if not isinstance(raw, list):
        errors.append("capabilities.yaml capabilities must be a list")
        return []
    capabilities: list[Capability] = []
    for item in raw:
        try:
            capabilities.append(Capability.model_validate(item))
        except ValidationError as exc:
            errors.append(f"capability schema error: {_compact_validation(exc)}")
    if len(capabilities) != 20:
        errors.append(f"expected 20 capabilities, found {len(capabilities)}")
    return capabilities


def _items(documents: dict[Path, dict[str, Any]], key: str) -> list[TraceableItem]:
    items: list[TraceableItem] = []
    for document in documents.values():
        raw = document.get(key)
        if isinstance(raw, list):
            for value in raw:
                if isinstance(value, dict) and "id" in value:
                    items.append(TraceableItem.model_validate(value))
    return items


def _validate_unique_ids(documents: dict[Path, dict[str, Any]], errors: list[str]) -> None:
    seen: dict[str, Path] = {}
    for path, document in documents.items():
        for item_id in _walk_ids(document):
            previous = seen.get(item_id)
            if previous is not None:
                errors.append(f"duplicate id {item_id}: {previous} and {path}")
            else:
                seen[item_id] = path


def _walk_ids(value: object) -> list[str]:
    ids: list[str] = []
    if isinstance(value, dict):
        item_id = value.get("id")
        if isinstance(item_id, str):
            ids.append(item_id)
        for child in value.values():
            ids.extend(_walk_ids(child))
    elif isinstance(value, list):
        for child in value:
            ids.extend(_walk_ids(child))
    return ids


def _validate_source_refs(documents: dict[Path, dict[str, Any]], source_ids: set[str], errors: list[str]) -> None:
    for path, document in documents.items():
        for source_ref in _walk_source_refs(document):
            if source_ref not in source_ids:
                errors.append(f"unresolved source_ref {source_ref}: {path}")


def _walk_source_refs(value: object) -> list[str]:
    refs: list[str] = []
    if isinstance(value, dict):
        raw = value.get("source_refs")
        if isinstance(raw, list):
            refs.extend(str(item) for item in raw)
        for child in value.values():
            refs.extend(_walk_source_refs(child))
    elif isinstance(value, list):
        for child in value:
            refs.extend(_walk_source_refs(child))
    return refs


def _validate_capability_dependencies(capabilities: list[Capability], capability_ids: set[str], errors: list[str]) -> None:
    for capability in capabilities:
        for dependency in capability.depends_on:
            if dependency not in capability_ids:
                errors.append(f"{capability.id} depends on unknown capability {dependency}")


def _validate_capability_refs(item: TraceableItem, capability_ids: set[str], errors: list[str]) -> None:
    refs = [*item.capabilities]
    if item.capability:
        refs.append(item.capability)
    for capability_id in refs:
        if capability_id not in capability_ids:
            errors.append(f"{item.id} references unknown capability {capability_id}")


def _validate_interfaces(items: list[TraceableItem], component_ids: set[str], errors: list[str]) -> None:
    for item in items:
        if item.from_component not in component_ids:
            errors.append(f"{item.id} references unknown from_component {item.from_component}")
        if item.to_component not in component_ids:
            errors.append(f"{item.id} references unknown to_component {item.to_component}")


def _validate_feature_refs(
    features: list[TraceableItem],
    epic_ids: set[str],
    requirement_ids: set[str],
    errors: list[str],
) -> None:
    for feature in features:
        epic = getattr(feature, "epic", None)
        if isinstance(epic, str) and epic not in epic_ids:
            errors.append(f"{feature.id} references unknown epic {epic}")
        for requirement_id in feature.requirements:
            if requirement_id not in requirement_ids:
                errors.append(f"{feature.id} references unknown requirement {requirement_id}")


def _item_id(item: TraceableItem) -> str:
    return item.id


def _unresolved_decisions(documents: dict[Path, dict[str, Any]]) -> list[str]:
    unresolved: list[str] = []
    for document in documents.values():
        decisions = document.get("decisions")
        if isinstance(decisions, list):
            for decision in decisions:
                if isinstance(decision, dict) and decision.get("status") in {"open", "unresolved"}:
                    unresolved.append(str(decision.get("id", "unknown")))
    return sorted(unresolved)


def _compact_validation(exc: ValidationError) -> str:
    first = exc.errors()[0]
    loc = ".".join(str(part) for part in first.get("loc", ()))
    message = str(first.get("msg", "validation failed"))
    return f"{loc}: {message}" if loc else message
