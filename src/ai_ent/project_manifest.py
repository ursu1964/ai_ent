def dry_run_evaluated_plan(plan: ImplementationPlan, evaluation: FeasibilityEvaluation) -> ImplementationDryRun:
    findings: list[DryRunFinding] = []
    findings.extend(_dry_run_precondition_findings(plan, evaluation))
    execution_prerequisites = tuple(
        sorted({condition for result in evaluation.task_results for condition in result.conditions})
    )
    findings.extend(
        DryRunFinding(
            f"DRYRUN-PREREQ-{index:03d}",
            "EXECUTION_PREREQUISITE",
            "execution",
            prerequisite,
        )
        for index, prerequisite in enumerate(execution_prerequisites, start=1)
    )
    theoretical_width = plan.as_dict()["summary"]["maximum_parallel_width"]
    effective_width = evaluation.feasible_parallel_width
    write_scope_conflicts = _write_scope_conflicts(plan)
    batches = _execution_batches(plan, effective_width)
    import_preview = tuple(_task_import_preview(task) for task in plan.tasks)
    recovery_points = (
        "before_task",
        "after_claim",
        "after_executor",
        "after_verification",
        "after_verified_commit",
        "after_db_completion",
        "between_batches",
        "at_human_gates",
    )
    repair_path_coverage = tuple(sorted(task.id for task in plan.tasks))
    if len(repair_path_coverage) != len(plan.tasks):
        findings.append(DryRunFinding("DRYRUN-REPAIR-COVERAGE", "ERROR", "repair", "not every task has repair path coverage"))
    if evaluation.plan_status == "BLOCKED":
        findings.append(DryRunFinding("DRYRUN-FEASIBILITY-BLOCKED", "ERROR", "feasibility", "technical blockers prevent dry-run freeze"))
    if evaluation.plan_status == "INVALID":
        findings.append(DryRunFinding("DRYRUN-FEASIBILITY-INVALID", "ERROR", "feasibility", "plan feasibility is invalid"))
    state = _plan_acceptance_state(findings, execution_prerequisites, evaluation)
    frozen_state: FrozenPlanState = "FROZEN" if state in {"READY_FOR_PLAN_ACCEPTANCE", "READY_WITH_EXECUTION_PREREQUISITES"} else "INVALIDATED"
    dependency_graph_hash = hashlib.sha256(canonical_bytes([list(edge) for edge in plan.dependency_edges])).hexdigest()
    dry_payload = {
        "compiled_project_hash": plan.source_compiled_hash,
        "capability_resolution_hash": plan.capability_resolution_hash,
        "trace_validation_hash": plan.trace_validation_hash,
        "implementation_plan_hash": plan.implementation_plan_hash,
        "feasibility_hash": evaluation.feasibility_hash,
        "dry_runner_version": DRY_RUNNER_VERSION,
        "plan_acceptance_state": state,
        "frozen_plan_state": frozen_state,
        "dependency_edge_count": len(plan.dependency_edges),
        "wave_count": len(plan.waves),
        "theoretical_parallel_width": theoretical_width,
        "effective_parallel_width": effective_width,
        "execution_batches": [batch.as_dict() for batch in batches],
        "task_import_preview": [preview.as_dict() for preview in import_preview],
        "recovery_points": list(recovery_points),
        "repair_path_coverage": list(repair_path_coverage),
        "write_scope_conflicts": list(write_scope_conflicts),
        "execution_prerequisites": list(execution_prerequisites),
        "findings": [finding.as_dict() for finding in sorted(findings, key=lambda item: item.finding_id)],
    }
    dry_run_hash = hashlib.sha256(canonical_bytes(dry_payload)).hexdigest()
    lock = ImplementationPlanLock(
        plan_id=f"PLAN-{plan.implementation_plan_hash[:12]}",
        plan_version="1",
        project_id="PRJ-AI-ENT",
        compiled_project_hash=plan.source_compiled_hash,
        capability_resolution_hash=plan.capability_resolution_hash,
        trace_validation_hash=plan.trace_validation_hash,
        implementation_plan_hash=plan.implementation_plan_hash,
        feasibility_hash=evaluation.feasibility_hash,
        dry_run_hash=dry_run_hash,
        task_generator_version=plan.generator_version,
        feasibility_evaluator_version=evaluation.evaluator_version,
        dry_runner_version=DRY_RUNNER_VERSION,
        task_fingerprints={task.id: task.fingerprint for task in plan.tasks},
        dependency_graph_hash=dependency_graph_hash,
        human_gate_definitions=plan.human_gates,
        effective_concurrency=effective_width,
        execution_prerequisites=execution_prerequisites,
        state=frozen_state,
    )
    return ImplementationDryRun(
        compiled_project_hash=plan.source_compiled_hash,
        capability_resolution_hash=plan.capability_resolution_hash,
        trace_validation_hash=plan.trace_validation_hash,
        implementation_plan_hash=plan.implementation_plan_hash,
        feasibility_hash=evaluation.feasibility_hash,
        dry_runner_version=DRY_RUNNER_VERSION,
        dry_run_hash=dry_run_hash,
        plan_acceptance_state=state,
        frozen_plan_state=frozen_state,
        dependency_edge_count=len(plan.dependency_edges),
        wave_count=len(plan.waves),
        theoretical_parallel_width=theoretical_width,
        effective_parallel_width=effective_width,
        execution_batches=batches,
        import_preview=import_preview,
        recovery_points=recovery_points,
        repair_path_coverage=repair_path_coverage,
        write_scope_conflicts=write_scope_conflicts,
        execution_prerequisites=execution_prerequisites,
        findings=tuple(sorted(findings, key=lambda item: item.finding_id)),
        lock=lock,
    )


