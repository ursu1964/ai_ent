def validate_compiled_traces(
    compilation: CompilationResult,
    resolution: CapabilityResolution,
) -> TraceValidationResult:
    compiled = compilation.compiled
    capability_by_id = {capability.capability_id: capability for capability in resolution.capabilities}
    components = [dict(item) for item in compiled.architecture.get("components", [])]
    interfaces = [dict(item) for item in compiled.architecture.get("interfaces", [])]
    gates = [dict(item) for item in compiled.verification.get("verification", {}).get("gates", [])]
    decisions = [dict(item) for item in compilation.compiled.as_dict().get("planning", {}).get("decisions", [])]
    requirements = [dict(item) for item in compiled.requirements]
    deployment_mode = str(compiled.deployment.get("deployment", {}).get("current_mode", ""))

    edges: list[TraceEdge] = []
    paths: list[TracePath] = []
    findings: list[TraceFinding] = []
    gaps: set[str] = set()

    component_by_capability = _items_by_capability(components)
    interface_by_component = _interfaces_by_component(interfaces)
    gates_by_source = _items_by_source(gates)

    for requirement in sorted(requirements, key=lambda item: str(item.get("id", ""))):
        requirement_id = str(requirement["id"])
        classification = requirement.get("classification")
        if classification == "FUTURE/DEFERRED":
            paths.append(
                TracePath(requirement_id, "DEFERRED", tuple(requirement.get("capabilities", [])), (), (), (), ())
            )
            findings.append(
                TraceFinding(
                    f"TRACE-{requirement_id}-DEFERRED",
                    "INFO",
                    requirement_id,
                    "requirement deferred from current implementation",
                )
            )
            continue
        capabilities = tuple(sorted(str(item) for item in requirement.get("capabilities", [])))
        components_for_requirement = tuple(sorted({
            component_id
            for capability_id in capabilities
            for component_id in component_by_capability.get(capability_id, set())
        }))
        interfaces_for_requirement = tuple(sorted({
            interface_id
            for component_id in components_for_requirement
            for interface_id in interface_by_component.get(component_id, set())
        }))
        verification_for_requirement = tuple(sorted({
            gate_id
            for source_ref in requirement.get("source_refs", [])
            for gate_id in gates_by_source.get(str(source_ref), set())
        }))
        evidence = tuple(sorted({
            evidence_ref
            for capability_id in capabilities
            for evidence_ref in capability_by_id.get(capability_id, _empty_capability(capability_id)).evidence_refs
        }))
        for capability_id in capabilities:
            edges.append(TraceEdge(requirement_id, capability_id, "REQUIRES_CAPABILITY"))
        for component_id in components_for_requirement:
            edges.append(TraceEdge(requirement_id, component_id, "IMPLEMENTED_BY_COMPONENT"))
        for interface_id in interfaces_for_requirement:
            edges.append(TraceEdge(requirement_id, interface_id, "EXPOSED_BY_INTERFACE"))
        for gate_id in verification_for_requirement:
            edges.append(TraceEdge(requirement_id, gate_id, "VERIFIED_BY"))
        for evidence_ref in evidence:
            edges.append(TraceEdge(requirement_id, evidence_ref, "EVIDENCED_BY"))

        coverage = _requirement_coverage(
            requirement,
            capabilities,
            components_for_requirement,
            verification_for_requirement,
            capability_by_id,
        )
        paths.append(
            TracePath(
                requirement_id,
                coverage,
                capabilities,
                components_for_requirement,
                interfaces_for_requirement,
                verification_for_requirement,
                evidence,
            )
        )
        _requirement_findings(
            requirement,
            coverage,
            components_for_requirement,
            verification_for_requirement,
            capability_by_id,
            findings,
            gaps,
            deployment_mode,
        )

    architecture = _architecture_coverage(components, interfaces, requirements, decisions, edges, findings)
    payload = {
        "source_compiled_hash": compilation.lock.compiled_hash,
        "capability_resolution_hash": resolution.capability_resolution_hash,
        "trace_validator_version": TRACE_VALIDATOR_VERSION,
        "trace_edges": [edge.as_dict() for edge in sorted(edges, key=lambda item: (item.source_id, item.edge_type, item.target_id))],
        "trace_paths": [path.as_dict() for path in sorted(paths, key=lambda item: item.requirement_id)],
        "architecture_coverage": [item.as_dict() for item in sorted(architecture, key=lambda item: (item.item_type, item.item_id))],
        "findings": [finding.as_dict() for finding in sorted(findings, key=lambda item: item.finding_id)],
        "implementation_gaps": sorted(gaps),
    }
    trace_hash = hashlib.sha256(canonical_bytes(payload)).hexdigest()
    return TraceValidationResult(
        source_compiled_hash=compilation.lock.compiled_hash,
        capability_resolution_hash=resolution.capability_resolution_hash,
        trace_validator_version=TRACE_VALIDATOR_VERSION,
        trace_validation_hash=trace_hash,
        trace_edges=tuple(TraceEdge(**item) for item in payload["trace_edges"]),
        trace_paths=tuple(TracePath(**item) for item in payload["trace_paths"]),
        architecture_coverage=tuple(ArchitectureTrace(**item) for item in payload["architecture_coverage"]),
        findings=tuple(TraceFinding(**item) for item in payload["findings"]),
        implementation_gaps=tuple(payload["implementation_gaps"]),
    )


