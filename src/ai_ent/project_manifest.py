def evaluate_implementation_plan_feasibility(
    plan: ImplementationPlan,
    environment: EnvironmentProfile,
    policy: FeasibilityPolicyProfile,
) -> FeasibilityEvaluation:
    preliminary = tuple(_evaluate_task_feasibility(task, plan, environment, policy) for task in plan.tasks)
    blocked_tasks = {result.task_id for result in preliminary if result.status == "BLOCKED"}
    propagated: list[TaskFeasibility] = []
    for result in preliminary:
        blocked_dependencies = tuple(
            dependency
            for dependency in _task_by_id(plan.tasks)[result.task_id].depends_on
            if dependency in blocked_tasks
        )
        if blocked_dependencies and result.status != "BLOCKED":
            propagated.append(_block_task_by_dependency(result, blocked_dependencies))
        else:
            propagated.append(result)
    task_results = tuple(sorted(propagated, key=lambda item: item.task_id))
    technical_blockers = tuple(
        sorted(
            {
                blocker
                for result in task_results
                for blocker in result.blockers
                if not blocker.startswith("HUMAN_GATE:")
            }
        )
    )
    if any(finding.severity == "ERROR" for finding in plan.findings):
        plan_status: PlanFeasibilityStatus = "INVALID"
    elif any(result.status == "BLOCKED" for result in task_results):
        plan_status = "BLOCKED"
    elif any(result.status == "HUMAN_APPROVAL_REQUIRED" for result in task_results):
        plan_status = "READY_WITH_HUMAN_GATES"
    else:
        plan_status = "READY_FOR_DRY_RUN"
    feasible_parallel_width = _feasible_parallel_width(plan, task_results, policy)
    findings = tuple(sorted((*plan.findings, *_feasibility_findings(task_results)), key=lambda item: item.finding_id))
    payload = {
        "implementation_plan_hash": plan.implementation_plan_hash,
        "source_compiled_hash": plan.source_compiled_hash,
        "capability_resolution_hash": plan.capability_resolution_hash,
        "trace_validation_hash": plan.trace_validation_hash,
        "evaluator_version": FEASIBILITY_EVALUATOR_VERSION,
        "environment_profile": environment.as_dict(),
        "policy_profile": policy.as_dict(),
        "task_results": [result.as_dict() for result in task_results],
        "human_gates": list(plan.human_gates),
        "feasible_parallel_width": feasible_parallel_width,
        "technical_blockers": list(technical_blockers),
        "findings": [finding.as_dict() for finding in findings],
        "plan_status": plan_status,
    }
    feasibility_hash = hashlib.sha256(canonical_bytes(payload)).hexdigest()
    return FeasibilityEvaluation(
        implementation_plan_hash=plan.implementation_plan_hash,
        source_compiled_hash=plan.source_compiled_hash,
        capability_resolution_hash=plan.capability_resolution_hash,
        trace_validation_hash=plan.trace_validation_hash,
        evaluator_version=FEASIBILITY_EVALUATOR_VERSION,
        feasibility_hash=feasibility_hash,
        plan_status=plan_status,
        environment_profile=environment,
        policy_profile=policy,
        task_results=task_results,
        human_gates=plan.human_gates,
        feasible_parallel_width=feasible_parallel_width,
        technical_blockers=technical_blockers,
        findings=findings,
    )


