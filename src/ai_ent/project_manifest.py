def generate_compiled_implementation_plan(
    compilation: CompilationResult,
    resolution: CapabilityResolution,
    trace: TraceValidationResult,
) -> ImplementationPlan:
    if not trace.ok:
        raise ValueError("trace validation failed; implementation DAG generation is blocked")

    compiled = compilation.compiled
    capabilities = {capability.capability_id: capability for capability in resolution.capabilities}
    components = {
        str(component["id"]): component
        for component in compiled.architecture.get("components", [])
        if component.get("classification") != "FUTURE/DEFERRED"
    }
    component_by_capability = _items_by_capability(list(components.values()))
    requirements_by_capability = _requirements_by_capability([dict(requirement) for requirement in compiled.requirements])
    trace_path_by_requirement = {path.requirement_id: path for path in trace.trace_paths}

    gap_capabilities = tuple(
        capability_id
        for capability_id in sorted(trace.implementation_gaps)
        if capabilities[capability_id].satisfaction not in {"DEFERRED", "NOT_APPLICABLE", "SATISFIED"}
    )
    epics = _planned_epics(compiled, gap_capabilities)
    features = _planned_features(compiled, gap_capabilities)
    satisfied_units = _satisfied_planning_units(resolution)
    task_specs = _generated_task_specs(
        compilation,
        resolution,
        trace,
        gap_capabilities,
        capabilities,
        components,
        component_by_capability,
        requirements_by_capability,
        trace_path_by_requirement,
    )
    tasks_without_dependencies = tuple(_task_from_spec(spec) for spec in task_specs)
    dependency_edges = _implementation_dependency_edges(tasks_without_dependencies, resolution)
    dependency_by_task: dict[str, tuple[str, ...]] = {
        task.id: tuple(sorted(dependency for task_id, dependency in dependency_edges if task_id == task.id))
        for task in tasks_without_dependencies
    }
    tasks = tuple(
        _replace_task_dependencies(task, dependency_by_task.get(task.id, ()))
        for task in tasks_without_dependencies
    )
    findings = _validate_implementation_plan(tasks, dependency_edges, gap_capabilities)
    if any(finding.severity == "ERROR" for finding in findings):
        raise ValueError("generated implementation DAG is invalid")
    waves = _implementation_waves(tasks, dependency_edges)
    parallelizable_sets = _parallelizable_sets(tasks, waves)
    critical_path = _critical_path(tasks, dependency_edges)
    human_gates = _human_gates(tasks)
    warning_classifications = _classify_trace_warnings(trace.findings)
    payload = {
        "source_compiled_hash": compilation.lock.compiled_hash,
        "capability_resolution_hash": resolution.capability_resolution_hash,
        "trace_validation_hash": trace.trace_validation_hash,
        "generator_version": IMPLEMENTATION_DAG_GENERATOR_VERSION,
        "epics": epics,
        "features": features,
        "tasks": [task.as_dict() for task in tasks],
        "satisfied_units": [unit.as_dict() for unit in satisfied_units],
        "dependency_edges": [list(edge) for edge in dependency_edges],
        "waves": waves,
        "parallelizable_sets": parallelizable_sets,
        "critical_path": list(critical_path),
        "human_gates": human_gates,
        "findings": [finding.as_dict() for finding in findings],
        "warning_classifications": [warning.as_dict() for warning in warning_classifications],
    }
    plan_hash = hashlib.sha256(canonical_bytes(payload)).hexdigest()
    return ImplementationPlan(
        source_compiled_hash=compilation.lock.compiled_hash,
        capability_resolution_hash=resolution.capability_resolution_hash,
        trace_validation_hash=trace.trace_validation_hash,
        generator_version=IMPLEMENTATION_DAG_GENERATOR_VERSION,
        implementation_plan_hash=plan_hash,
        epics=tuple(epics),
        features=tuple(features),
        tasks=tasks,
        satisfied_units=satisfied_units,
        dependency_edges=dependency_edges,
        waves=tuple(waves),
        parallelizable_sets=tuple(parallelizable_sets),
        critical_path=critical_path,
        human_gates=tuple(human_gates),
        findings=findings,
        warning_classifications=warning_classifications,
    )


